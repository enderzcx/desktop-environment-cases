"""Validate case data, generate reading views, and search without executing cases."""

import argparse
import json
from pathlib import Path
from urllib.parse import urlsplit

from jsonschema import Draft202012Validator, FormatChecker

ROOT = Path(__file__).resolve().parents[1]
SCHEMA = json.loads((ROOT / "schema/case.schema.json").read_text(encoding="utf-8"))
Draft202012Validator.check_schema(SCHEMA)
VALIDATOR = Draft202012Validator(SCHEMA, format_checker=FormatChecker())
STATUS = {"reported": "待复现", "confirmed": "根因已确认", "superseded": "已被取代"}


def validate_case(case):
    VALIDATOR.validate(case)
    evidence = {item["id"]: item for item in case["evidence"]}
    if len(evidence) != len(case["evidence"]):
        raise ValueError("duplicate evidence id")
    for item in [case["cause"], *case["remediations"]]:
        if not set(item["evidence_ids"]).issubset(evidence):
            raise ValueError("unknown evidence reference")
    if case["status"] == "confirmed":
        references = [evidence[key] for key in case["cause"]["evidence_ids"]]
        if case["cause"]["confidence"] != "confirmed" or not any(
            item["type"] in {"reproduction", "source_analysis"} for item in references
        ):
            raise ValueError("confirmed requires root-cause reproduction or source analysis")
    for item in evidence.values():
        reference = item.get("reference")
        if item["type"] in {"vendor_documentation", "source_analysis", "ci"} and not reference:
            raise ValueError("external evidence requires a reference")
        if reference:
            url = urlsplit(reference)
            if url.scheme != "https" or not url.hostname or url.username or url.password or url.query:
                raise ValueError("use an HTTPS source link without credentials or query parameters")
    reproducer = case.get("reproducer")
    if reproducer and Path(reproducer["path"]).stem != case["id"] + ".test":
        raise ValueError("reproducer must belong to this case")


def load_cases():
    cases = []
    for path in sorted((ROOT / "cases").glob("*.json")):
        case = json.loads(path.read_text(encoding="utf-8"))
        validate_case(case)
        if path.stem != case["id"]:
            raise ValueError(f"{path.name}: filename must equal case id")
        if "reproducer" in case:
            fixture = ROOT / case["reproducer"]["path"]
            if not fixture.resolve().is_relative_to(ROOT) or not fixture.is_file():
                raise ValueError(f"{case['id']}: missing or external reproducer")
        cases.append(case)
    if not cases or len({case["id"] for case in cases}) != len(cases):
        raise ValueError("catalog must contain cases with unique ids")
    return cases


def bullets(items):
    return "\n".join("- " + item for item in items)


def render_case(case):
    parts = [
        "<!-- Generated by tools/catalog.py. Edit cases/" + case["id"] + ".json. -->",
        f"# {case['id']} · {case['title']}",
        f"状态：{STATUS[case['status']]} · 更新：{case['updated_at']}",
        f"平台：{', '.join(case['platforms'])} · 产品：{', '.join(case['products'])}",
        case["summary"],
        "## 症状", bullets(case["symptoms"]),
        "## 已知环境", bullets(case["environment"]),
        "## 根因", case["cause"]["summary"],
        f"确认程度：`{case['cause']['confidence']}`；证据：{', '.join(case['cause']['evidence_ids']) or '暂无'}。",
        "## 检测", bullets(case["detection"]["checks"]),
        "### 排除条件", bullets(case["detection"]["exclusions"]),
        "## 处理方法",
    ]
    for number, action in enumerate(case["remediations"], 1):
        parts += [
            f"### {number}. {action['description']}",
            f"类型：`{action['kind']}`；证据：{', '.join(action['evidence_ids']) or '暂无'}。",
            "步骤：", bullets(action["steps"]),
            "复检：", bullets(action["verification"]),
            "风险：", bullets(action["risks"]),
        ]
    parts += ["## 证据"]
    for item in case["evidence"]:
        parts += [f"### {item['id']} · {item['type']} · {item['observed_at']}", item["summary"], "证明范围：" + item["scope"]]
        if "reference" in item:
            parts.append(f"[来源]({item['reference']})")
    parts += ["## 尚未验证与限制", bullets(case["limitations"])]
    if "reproducer" in case:
        fixture = case["reproducer"]
        parts += ["## 最小复现", fixture["scope"], f"```sh\n{fixture['command']}\n```", f"[查看复现代码](../../{fixture['path']})"]
    parts += [f"[结构化记录](../../cases/{case['id']}.json) · [返回索引](../INDEX.md)"]
    return "\n\n".join(parts) + "\n"


def generated_files(cases):
    index = {"schema_version": 1, "cases": []}
    lines = ["<!-- Generated by tools/catalog.py. -->", "# 案例索引", "根因确认、修复发布与客户验收分别记录；请阅读案例的证据和限制。"]
    files = {}
    for status, label in STATUS.items():
        lines += ["## " + label]
        entries = [case for case in cases if case["status"] == status]
        lines.append(bullets([f"[{case['id']} · {case['title']}](cases/{case['id']}.md) — {', '.join(case['platforms'])}" for case in entries]) if entries else "暂无案例。")
    for case in cases:
        index["cases"].append({**{key: case[key] for key in ("id", "title", "category", "platforms", "products", "keywords", "status", "updated_at")}, "record": f"cases/{case['id']}.json", "document": f"docs/cases/{case['id']}.md"})
        files[Path(f"docs/cases/{case['id']}.md")] = render_case(case)
    files[Path("catalog.json")] = json.dumps(index, ensure_ascii=False, indent=2) + "\n"
    files[Path("docs/INDEX.md")] = "\n\n".join(lines) + "\n"
    return files


def matches(case, query, platform=None, confirmed=False):
    return ((not platform or platform in case["platforms"])
            and (not confirmed or case["status"] == "confirmed")
            and query.casefold() in json.dumps(case, ensure_ascii=False).casefold())


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("command", choices=["build", "check", "search"])
    parser.add_argument("query", nargs="?", default="")
    parser.add_argument("--platform", choices=["windows", "macos", "linux"])
    parser.add_argument("--confirmed", action="store_true")
    args = parser.parse_args()
    cases = load_cases()
    if args.command == "search":
        for case in cases:
            if matches(case, args.query, args.platform, args.confirmed):
                print(f"{case['id']} [{STATUS[case['status']]}] {case['title']} -> docs/cases/{case['id']}.md")
        return
    expected = generated_files(cases)
    extras = set((ROOT / "docs/cases").glob("*.md")) - {ROOT / path for path in expected}
    if extras:
        raise ValueError("orphaned generated documents: " + ", ".join(str(path.relative_to(ROOT)) for path in sorted(extras)))
    for path, content in expected.items():
        destination = ROOT / path
        if args.command == "build":
            destination.parent.mkdir(parents=True, exist_ok=True)
            destination.write_text(content, encoding="utf-8")
        elif not destination.is_file() or destination.read_text(encoding="utf-8") != content:
            raise ValueError(f"stale generated file: {path}; run tools/catalog.py build")
    print(f"{args.command}: {len(cases)} cases validated")


if __name__ == "__main__":
    main()
